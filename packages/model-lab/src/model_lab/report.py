"""Report writing: reports/<date>/results.json and summary.md (Requirement 2.4).

Reports never contain raw paths. Before writing, the text is checked for every dataset
root, for absolute POSIX or Windows paths and for home folders; a hit stops the write.
"""

from __future__ import annotations

import json
import re
from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    import datetime as dt
    from pathlib import Path

_PATHLIKE: Final = re.compile(r"(?<![\w.])(/(home|Users|root|tmp|mnt|media|data)/|[A-Za-z]:\\)")


class ReportError(ValueError):
    """The report would leak a path."""


def check_no_paths(text: str, forbidden: list[Path]) -> None:
    """Raise ReportError if text contains a dataset root or an absolute path."""
    for root in forbidden:
        if str(root) and str(root) in text:
            msg = "report contains a dataset path"
            raise ReportError(msg)
    if _PATHLIKE.search(text):
        msg = "report contains an absolute path"
        raise ReportError(msg)


def _fmt(value: object, percent: bool = False) -> str:  # noqa: FBT001, FBT002
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{100 * value:.1f} %" if percent else f"{value:.3f}"
    return str(value)


def summary_markdown(results: dict[str, object], date: dt.date, label: str) -> str:
    """Human-readable summary of results.json."""
    title = f"# Model evaluation, {date.isoformat()}"
    lines = [title + (f" ({label})" if label else ""), ""]
    lines += [
        f"- Datasets: {', '.join(results['datasets'])}",  # type: ignore[arg-type]
        f"- Codec conditions: {', '.join(results['conditions'])}",  # type: ignore[arg-type]
        f"- Items: {results['items']}",
        "- Scores are calibrated Dissonance_Scores; rates use score >= the possession threshold.",
        "- Smoothed rates: share of windows in Possession after the detector's EMA and hysteresis.",
        "- Generated by `mise run model:eval`; numbers come only from this run.",
        "",
    ]
    for candidate in results["candidates"]:  # type: ignore[attr-defined]
        cal = candidate["calibration"]
        lat = candidate["latencyMs"]
        lines += [
            f"## {candidate['candidate']}",
            "",
            f"- Model SHA-256: `{candidate['modelSha256']}`",
            f"- Temperature: {cal['temperature']} (fitted on: {cal['fittedOn']})",
            f"- Possession threshold: {candidate['possessionThreshold']}",
            (
                f"- Latency per window, {lat['runtime']}: p50 {_fmt(lat['p50'])} ms, "
                f"p95 {_fmt(lat['p95'])} ms ({lat['windows']} windows)"
            ),
            "",
            (
                "| Dataset | Condition | Genuine | Synthetic | AUC | EER | False alarms | Detected "
                "| False alarms (smoothed) | Detected (smoothed) | ECE before | ECE after |"
            ),
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        lines += [
            f"| {r['dataset']} | {r['condition']} | {r['genuine']} | {r['synthetic']} "
            f"| {_fmt(r['auc'])} | {_fmt(r['eer'], percent=True)} "
            f"| {_fmt(r['falseAlarmRate'], percent=True)} "
            f"| {_fmt(r['detectionRate'], percent=True)} "
            f"| {_fmt(r.get('falseAlarmRateSmoothed'), percent=True)} "
            f"| {_fmt(r.get('detectionRateSmoothed'), percent=True)} "
            f"| {_fmt(r['eceBefore'])} | {_fmt(r['eceAfter'])} |"
            for r in candidate["results"]
        ]
        lines.append("")
    web = results.get("webLatency")
    if isinstance(web, dict):
        lines += [
            "## ONNX Runtime Web latency",
            "",
            (
                f"- {web.get('runtime')}: p50 {_fmt(web.get('p50'))} ms, "
                f"p95 {_fmt(web.get('p95'))} ms ({web.get('windows')} windows, model "
                f"{web.get('model')})"
            ),
            "",
        ]
    return "\n".join(lines)


def read_web_latency(path: Path) -> dict[str, object]:
    """Read the bench-web result written by the Playwright benchmark."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        msg = "web latency file must hold a JSON object"
        raise ReportError(msg)
    keep = ("runtime", "model", "windows", "p50", "p95", "userAgent")
    return {k: data[k] for k in keep if k in data}


def write(
    results: dict[str, object],
    reports_dir: Path,
    date: dt.date,
    label: str = "",
    forbidden: list[Path] | None = None,
) -> Path:
    """Write both files into reports_dir/<date>/ and return that folder."""
    body = json.dumps({"date": date.isoformat(), "label": label, **results}, indent=2) + "\n"
    summary = summary_markdown(results, date, label) + "\n"
    for text in (body, summary):
        check_no_paths(text, forbidden or [])
    folder = reports_dir / date.isoformat()
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "results.json").write_text(body, encoding="utf-8")
    (folder / "summary.md").write_text(summary, encoding="utf-8")
    return folder
