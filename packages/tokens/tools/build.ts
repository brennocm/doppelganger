/**
 * Token build (haunted-ui Requirement 7): tokens.json → generated/tokens.css and
 * generated/tokens.ts, plus the contrast report. Exits 1 when any pair in
 * contrast-pairs.json misses its target. Run with `node tools/build.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { argv, exit, stderr, stdout } from "node:process";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);

interface TypeRole {
  size: string;
  line: string;
  weight: number;
  family: string;
}
export interface Tokens {
  color: Record<string, string>;
  font: Record<string, string>;
  type: Record<string, TypeRole>;
  space: Record<string, string>;
  radius: Record<string, string>;
  motion: Record<string, string>;
  focus: Record<string, string>;
}
export interface Pair {
  fg: string;
  bg: string;
  target: number;
  use: string;
}

const HEX = /^#[0-9A-F]{6}$/;

function channel(v: number): number {
  const c = v / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  if (!HEX.test(hex)) throw new Error(`not an uppercase #RRGGBB color: ${hex}`);
  const n = Number.parseInt(hex.slice(1), 16);
  return (
    0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255)
  );
}

/** WCAG 2.x contrast ratio, from 1 to 21. */
export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

export function loadTokens(): { tokens: Tokens; pairs: Pair[] } {
  const tokens = JSON.parse(readFileSync(new URL("tokens.json", root), "utf8")) as Tokens;
  const pairs = (
    JSON.parse(readFileSync(new URL("contrast-pairs.json", root), "utf8")) as { pairs: Pair[] }
  ).pairs;
  return { tokens, pairs };
}

export interface PairResult extends Pair {
  ratio: number;
  ok: boolean;
}

export function checkPairs(tokens: Tokens, pairs: Pair[]): PairResult[] {
  return pairs.map((pair) => {
    const fg = tokens.color[pair.fg];
    const bg = tokens.color[pair.bg];
    if (fg === undefined || bg === undefined)
      throw new Error(`unknown color in pair ${pair.fg}/${pair.bg}`);
    const ratio = contrast(fg, bg);
    return { ...pair, ratio, ok: ratio >= pair.target };
  });
}

const BANNER = "Generated by packages/tokens/tools/build.ts from tokens.json. Do not edit.";

export function renderCss(t: Tokens): string {
  const lines: string[] = [`/* ${BANNER} */`, ":root {"];
  for (const [name, value] of Object.entries(t.color)) lines.push(`  --color-${name}: ${value};`);
  for (const [name, value] of Object.entries(t.font)) lines.push(`  --font-${name}: ${value};`);
  for (const [name, role] of Object.entries(t.type)) {
    lines.push(
      `  --type-${name}: ${role.weight} ${role.size}/${role.line} var(--font-${role.family});`,
    );
  }
  for (const [name, value] of Object.entries(t.space)) lines.push(`  --space-${name}: ${value};`);
  for (const [name, value] of Object.entries(t.radius)) lines.push(`  --radius-${name}: ${value};`);
  for (const [name, value] of Object.entries(t.motion)) lines.push(`  --${name}: ${value};`);
  for (const [name, value] of Object.entries(t.focus)) lines.push(`  --focus-${name}: ${value};`);
  // The Kiro page background: the only decorative gradient allowed (design-system steering).
  lines.push(
    "  --page-background: radial-gradient(60% 50% at 100% 100%, var(--color-bg-glow), transparent),",
    "    linear-gradient(180deg, var(--color-bg-top) 0%, var(--color-bg) 50%, var(--color-bg-deep) 100%);",
    "}",
    "",
  );
  return lines.join("\n");
}

export function renderTs(t: Tokens): string {
  return [
    `/* ${BANNER} */`,
    "",
    `export const tokens = ${JSON.stringify(t, null, 2)} as const;`,
    "",
    "export type ColorToken = keyof typeof tokens.color;",
    "",
  ].join("\n");
}

function main(): number {
  const { tokens, pairs } = loadTokens();
  const results = checkPairs(tokens, pairs);
  for (const r of results) {
    const line = `${r.ok ? "ok  " : "FAIL"} ${r.ratio.toFixed(2).padStart(5)}:1 ≥ ${r.target}  ${r.fg} on ${r.bg} (${r.use})\n`;
    (r.ok ? stdout : stderr).write(line);
  }
  const failed = results.filter((r) => !r.ok);
  if (failed.length > 0) {
    stderr.write(`tokens: ${failed.length} contrast pair(s) below target; nothing written\n`);
    return 1;
  }
  writeFileSync(new URL("generated/tokens.css", root), renderCss(tokens));
  writeFileSync(new URL("generated/tokens.ts", root), renderTs(tokens));
  stdout.write(`tokens: ${results.length} pairs meet their targets; wrote generated/\n`);
  return 0;
}

if (argv[1] === fileURLToPath(import.meta.url)) exit(main());
