#!/usr/bin/env bash
# Regenerate TS types and Pydantic models from packages/contracts/schemas/*.schema.json.
# Called by `mise run gen:contracts`. Output is deterministic (no timestamps).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)/packages/contracts"

ts_out=src/generated
py_out=src/doppelganger_contracts/generated
rm -rf "$ts_out" "$py_out"
mkdir -p "$ts_out" "$py_out"

banner='/* Generated by "mise run gen:contracts" from packages/contracts/schemas. Do not edit. */'
for schema in schemas/*.schema.json; do
  name="$(basename "$schema" .schema.json)"
  pnpm exec json2ts --input "$schema" --output "$ts_out/$name.ts" \
    --bannerComment "$banner" --additionalProperties false --unreachableDefinitions
done
{
  echo "$banner"
  for schema in schemas/*.schema.json; do
    echo "export type * from \"./$(basename "$schema" .schema.json).ts\";"
  done
} >"$ts_out/index.ts"

uv run --locked datamodel-codegen --input schemas --input-file-type jsonschema \
  --output "$py_out" --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.12 --disable-timestamp --use-standard-collections \
  --use-union-operator --field-constraints --use-double-quotes --use-title-as-name \
  --extra-fields forbid --formatters ruff-format \
  --custom-file-header '# Generated by "mise run gen:contracts" from packages/contracts/schemas. Do not edit.'
echo "gen:contracts: generated $ts_out and $py_out"
